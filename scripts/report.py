#!/usr/bin/env python3
"""Turn the measurements into the report, and splice the results into README.md.

  python3 scripts/report.py [--check]

Writes `REPORT.md` -- every database, both engines, the ratio -- and replaces the block between
`<!-- results:start -->` and `<!-- results:end -->` in `README.md` with the summary table. Both are
generated from `build/results.json`, so the numbers in the README are the numbers that were measured
and cannot be edited into something more flattering. `--check` exits non-zero if either is stale.
"""
import argparse, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT, human, load_results  # noqa: E402

REPORT = os.path.join(ROOT, "REPORT.md")
README = os.path.join(ROOT, "README.md")
START, END = "<!-- results:start -->", "<!-- results:end -->"
GENERATED = ("<!-- Generated by scripts/report.py from build/results.json.\n"
             "     Do not edit by hand: `make report` overwrites it. -->")


def rows(results):
    out = []
    for db in sorted(results):
        r = results[db]
        my, do = r.get("mysql_disk_bytes"), r.get("dolt_disk_bytes")
        if not my or not do:
            continue
        out.append(dict(db=db, mysql=my, dolt=do, ratio=do / my,
                        logical=r.get("mysql_logical_bytes") or 0,
                        dump=r.get("dump_bytes") or 0,
                        tables=r.get("tables") or 0, rows=r.get("rows_mysql") or 0,
                        mismatch=bool(r.get("row_mismatches")),
                        errors=r.get("dolt", {}).get("statement_error_count", 0)))
    return out


def summary_table(items):
    L = ["| database | rows | MySQL on disk | Dolt on disk | Dolt ÷ MySQL |",
         "|---|---:|---:|---:|---:|"]
    for i in sorted(items, key=lambda x: -x["mysql"]):
        L.append(f"| `{i['db']}` | {i['rows']:,} | {human(i['mysql'])} | {human(i['dolt'])} "
                 f"| **{i['ratio']:.2f}×** |")
    my, do = sum(i["mysql"] for i in items), sum(i["dolt"] for i in items)
    L.append(f"| **all {len(items)}** | **{sum(i['rows'] for i in items):,}** | **{human(my)}** "
             f"| **{human(do)}** | **{do / my:.2f}×** |")
    return "\n".join(L)


def report(items):
    my, do = sum(i["mysql"] for i in items), sum(i["dolt"] for i in items)
    smallest = min(items, key=lambda x: x["ratio"])
    largest = max(items, key=lambda x: x["ratio"])
    L = [GENERATED, "", "# Disk usage: MySQL 9.7.2 against Dolt 2.3.2", "",
         f"The same {len(items)} sample databases, {sum(i['rows'] for i in items):,} rows, loaded "
         "into both engines from the same `mysqldump` files and measured the same way: `du -sb` of "
         "the directory each engine keeps the database in.", "",
         f"**Dolt uses {human(do)} where MySQL uses {human(my)} — {do / my:.2f}× overall.** The "
         f"ratio is not uniform: it ranges from {smallest['ratio']:.2f}× (`{smallest['db']}`) to "
         f"{largest['ratio']:.2f}× (`{largest['db']}`).", "",
         "## Every database", "",
         "`MySQL on disk` and `Dolt on disk` are directory sizes. `MySQL logical` is what",
         "`information_schema` reports (`data_length + index_length`) — always smaller than the",
         "directory, because it does not count free pages in the tablespace. `Dump` is the",
         "`mysqldump` SQL both engines were loaded from, included as a size-independent reference",
         "point for how much data is actually there.", "",
         "| database | tables | rows | dump | MySQL logical | MySQL on disk | Dolt on disk | Dolt ÷ MySQL |",
         "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for i in sorted(items, key=lambda x: -x["mysql"]):
        L.append(f"| `{i['db']}` | {i['tables']} | {i['rows']:,} | {human(i['dump'])} "
                 f"| {human(i['logical'])} | {human(i['mysql'])} | {human(i['dolt'])} "
                 f"| **{i['ratio']:.2f}×** |")
    L.append(f"| **total** | {sum(i['tables'] for i in items)} | {sum(i['rows'] for i in items):,} "
             f"| {human(sum(i['dump'] for i in items))} | {human(sum(i['logical'] for i in items))} "
             f"| **{human(my)}** | **{human(do)}** | **{do / my:.2f}×** |")

    bad = [i for i in items if i["mismatch"]]
    L += ["", "## Is the comparison valid?", "",
          "Every table was counted with `COUNT(*)` on both sides before any size was recorded.",
          (f"**{len(bad)} database(s) disagree** and their ratios cannot be trusted: "
           + ", ".join(f"`{i['db']}`" for i in bad) if bad else
           "**Every table matches**, so both engines are holding the same rows."), ""]
    errs = [i for i in items if i["errors"]]
    if errs:
        L += ["Some statements in the dumps were rejected by Dolt. These are schema objects, not "
              "rows — the row counts above still match — but they are listed in `build/results.json` "
              "per database and summarised here:", "",
              "| database | statements Dolt rejected |", "|---|---:|"]
        L += [f"| `{i['db']}` | {i['errors']} |" for i in sorted(errs, key=lambda x: -x["errors"])]
        L.append("")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()

    results = load_results()
    items = rows(results)
    if not items:
        sys.exit("no measurements in build/results.json; run scripts/measure.py first")

    text = report(items)
    readme = open(README, encoding="utf-8").read() if os.path.exists(README) else ""
    new_readme = readme
    if START in readme and END in readme:
        head, rest = readme.split(START, 1)
        _, tail = rest.split(END, 1)
        new_readme = f"{head}{START}\n{summary_table(items)}\n{END}{tail}"

    if a.check:
        stale = []
        if not os.path.exists(REPORT) or open(REPORT, encoding="utf-8").read() != text:
            stale.append("REPORT.md")
        if new_readme != readme:
            stale.append("README.md")
        for s in stale:
            print(f"  x {s} is out of date; run `make report`")
        if stale:
            return 1
        print("  . REPORT.md and the README results are up to date")
        return 0

    open(REPORT, "w", encoding="utf-8").write(text)
    if new_readme != readme:
        open(README, "w", encoding="utf-8").write(new_readme)
    my, do = sum(i["mysql"] for i in items), sum(i["dolt"] for i in items)
    print(f"  . wrote REPORT.md: {len(items)} databases, MySQL {human(my)}, Dolt {human(do)}, "
          f"{do / my:.2f}x")
    return 0


if __name__ == "__main__":
    sys.exit(main())
